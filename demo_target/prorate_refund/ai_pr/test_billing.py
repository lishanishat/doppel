import pytest
from billing import prorate_refund as p


@pytest.mark.parametrize("args,expected", [
    (("30.00", "2026-04-01", "2026-05-01", "2026-04-10"), "20.00"),
    (("30.00", "2026-04-01", "2026-05-01", "2026-04-15"), "15.00"),
    (("10.00", "2026-04-01", "2026-05-01", "2026-04-04"), "8.67"),
    (("29.00", "2028-02-01", "2028-03-01", "2028-02-28"), "1.00"),
    (("29.00", "2028-02-01", "2028-03-01", "2028-02-29"), "0.00"),
    (("30.00", "2026-04-01", "2026-05-01", "2026-05-01"), "0.00"),
    (("30.00", "2026-04-01", "2026-05-01", "2026-03-25"), "30.00"),
    (("30.00", "2026-04-01", "2026-05-01", "2026-06-01"), "0.00"),
    (("12.5", "2026-04-01", "2026-05-01", "2026-03-01"), "12.50"),
    (("0", "2026-04-01", "2026-05-01", "2026-04-10"), "0.00"),
    (("0.01", "2026-04-01", "2026-04-03", "2026-04-01"), "0.01"),  # exact half rounds up
    (("0.01", "2026-04-01", "2026-04-04", "2026-04-01"), "0.01"),  # 0.00667 -> 0.01
    (("0.01", "2026-04-01", "2026-04-04", "2026-04-02"), "0.00"),
    (("1000000.00", "2026-04-01", "2026-05-01", "2026-04-30"), "0.00"),
])
def test_examples(args, expected):
    assert p(*args) == expected


@pytest.mark.parametrize("args", [
    ("abc", "2026-04-01", "2026-05-01", "2026-04-10"),
    ("", "2026-04-01", "2026-05-01", "2026-04-10"),
    ("-1.00", "2026-04-01", "2026-05-01", "2026-04-10"),
    ("1.234", "2026-04-01", "2026-05-01", "2026-04-10"),
    ("nan", "2026-04-01", "2026-05-01", "2026-04-10"),
    ("1e2", "2026-04-01", "2026-05-01", "2026-04-10"),
    ("30", "2026-4-01", "2026-05-01", "2026-04-10"),
    ("30", "2026-02-30", "2026-05-01", "2026-04-10"),
    ("30", "2026-04-01", "2026-05-01", "garbage"),
    ("30", "2026-04-01", "2026-04-01", "2026-04-01"),
    ("30", "2026-05-01", "2026-04-01", "2026-04-10"),
    ("30", "2026-05-01", "2026-04-01", "2026-06-10"),  # invalid even if cancel after
])
def test_invalid(args):
    with pytest.raises(ValueError):
        p(*args)
