import pytest
from billing import prorate_refund as f

S, E = "2026-04-01", "2026-05-01"


@pytest.mark.parametrize("price,s,e,c,r", [
    ("30.00", S, E, "2026-04-10", "20.00"),
    ("30.00", S, E, "2026-04-15", "15.00"),
    ("10.00", S, E, "2026-04-04", "8.67"),
    ("29.00", "2028-02-01", "2028-03-01", "2028-02-28", "1.00"),
    ("29.00", "2028-02-01", "2028-03-01", "2028-02-29", "0.00"),
    ("30.00", S, E, "2026-05-01", "0.00"),
    ("30.00", S, E, "2026-03-25", "30.00"),
    ("12.5", S, E, "2026-03-25", "12.50"),
    ("0", S, E, "2026-04-10", "0.00"),
    ("0.05", "2026-04-01", "2026-04-03", "2026-04-01", "0.03"),  # half up
    ("30.00", S, E, "2026-04-01", "29.00"),
    ("30.00", S, E, "2026-04-30", "0.00"),
])
def test_ok(price, s, e, c, r):
    assert f(price, s, e, c) == r


@pytest.mark.parametrize("args", [
    ("-1.00", S, E, S), ("1.001", S, E, S), ("abc", S, E, S), ("", S, E, S),
    ("1.", S, E, S), ("10", "2026-13-01", E, S), ("10", S, "bad", S),
    ("10", S, E, "2026-02-30"), ("10", E, S, S), ("10", S, S, S),
    ("10", S, E, "20260410"),
])
def test_invalid(args):
    with pytest.raises(ValueError):
        f(*args)
